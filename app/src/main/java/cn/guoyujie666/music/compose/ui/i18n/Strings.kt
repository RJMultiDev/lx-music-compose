    var currentLocale: String = "zh"

    fun get(key: String, vararg args: Pair<String, String>): String {
        val map = if (currentLocale.startsWith("zh")) zh else en
        return (map[key] ?: en[key] ?: key).let { s ->
            var result = s
            for ((k, v) in args) result = result.replace("{$k}", v)
            result
        }
    }
}

